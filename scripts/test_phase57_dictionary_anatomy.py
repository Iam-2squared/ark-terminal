 def test_fixed_rows_and_no_promotion(self):
  p=a.BASE/'diagnostic'
  if not p.exists():self.skipTest('diagnostic generated by CI before test')
  rows=a.read(p/'02_all_traits.json');self.assertEqual(len(rows),146);self.assertEqual(sum(r['status']=='WATCH' for r in rows),92)
  for lane in ['daily','intraday']:
   old={x['id']:x for x in a.read(a.SOURCE/(lane+'-reliability.json'))}
   for row in (x for x in rows if x['lane']==lane):
    for k,value in old[row['id']].items():self.assertEqual(row[k],value)
  self.assertFalse(a.read(p/'09_decision.json')['dictionaryReaderReadyForEntryExit'])
